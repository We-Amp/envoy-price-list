#!/usr/bin/env python3
"""W2B analysis (run w2b: shape s; arms pgolto, pgolto-A2, pgolto-relocs, bolt, autofdo, autofdo-order).

Usage: python3 -I analyse_w2b.py RUN_DIR OUT_MD [W2_RUN_DIR]
Intervals: the wider of t(n-1) x SE and 1.96 x sqrt(SE^2 + 0.34^2), on log ratios, shown as %.
The autofdo-order share of the pgolto gain is chained through the w2 run's opt/pgolto ratio on s
(labelled chained; needs W2_RUN_DIR).

Decision rules, fixed before the run ("gain" = minus the effect vs the reference, in %):
  run           VALID when pgolto-A2 vs pgolto is within +-1%; INVALID otherwise, with no exception.
  .rodata move  pgolto-relocs vs pgolto (the --emit-relocs relink moves .rodata): when it is within
                +-1% and its |mean log ratio| is within the A/A reach (|mean| + t half-width of
                pgolto-A2 vs pgolto), the bolt gain over pgolto is BOLT's; otherwise bolt vs
                pgolto-relocs is the BOLT effect and the rest is the relink.
  BOLT          KILL further BOLT/Propeller work when bolt's gain vs pgolto-relocs is under 1.5%,
                else KEEP.
  autofdo+order KEEP when autofdo-order saves at least 3% vs autofdo, else not kept.
"""
import json
import math
import statistics as st
import sys
from collections import defaultdict

run, out = sys.argv[1], sys.argv[2]
w2 = sys.argv[3] if len(sys.argv) > 3 else None
A = json.load(open(run + "/results.json"))["analysis"]
legs = [json.loads(x) for x in open(run + "/legs.jsonl") if '"leg_id"' in x]
T = {4: 2.776, 5: 2.571, 6: 2.447, 7: 2.365, 8: 2.306}
SH = "s"


def rows(res, sh):
    return res["shapes"][sh]["comparisons"]


def get(res, sh, arm, ref):
    for c in rows(res, sh):
        r = c.get("reference") or c.get("ref")
        if c["arm"] == arm and r == ref:
            return list(c["cycles_total"]["paired"]["log_pcts"])
        if c["arm"] == ref and r == arm:
            return [-x for x in c["cycles_total"]["paired"]["log_pcts"]]
    return None


def pc(x):
    return (math.exp(x / 100) - 1) * 100


def stat(x):
    n = len(x)
    mu, se = st.mean(x), st.stdev(x) / math.sqrt(n)
    hw, whw = T.get(n - 1, 2.0) * se, 1.96 * math.sqrt(se ** 2 + 0.34 ** 2)
    w = max(hw, whw)
    return {"n": n, "mu": mu, "pct": pc(mu), "lo": pc(mu - w), "hi": pc(mu + w), "which": "t" if hw >= whw else "widened",
            "won": sum(v < 0 for v in x), "reach": abs(mu) + hw}


L = ["# W2B analysis (generated by analyse_w2b.py)", "",
     "Shape `s`; primary metric cycles (u+k) per response; effect = mean paired log ratio as %%; interval = the wider "
     "of t and widened (named). Rounds done: %s." % A.get("rounds_done"), "",
     "| comparison | effect | interval | won |", "|---|---|---|---|"]
P = [("pgolto-A2", "pgolto"), ("pgolto-relocs", "pgolto"), ("bolt", "pgolto-relocs"), ("bolt", "pgolto"),
     ("autofdo-order", "autofdo"), ("autofdo", "pgolto"), ("autofdo-order", "pgolto")]
S = {}
for a, r in P:
    x = get(A, SH, a, r)
    s = stat(x)
    S[(a, r)] = s
    L.append("| %s vs %s | %+.2f%% | [%+.2f, %+.2f] (%s) | %d/%d |" % (a, r, s["pct"], s["lo"], s["hi"], s["which"], s["won"], s["n"]))
aa = S[("pgolto-A2", "pgolto")]
L += ["", "A/A reach (|mean| + t half-width, log-%%): %.2f%%" % aa["reach"], "", "## Decision rules (fixed before the run)", ""]
v = []
aa_ok = abs(aa["pct"]) <= 1.0
v.append("- run: pgolto-A2 vs pgolto %+.2f%% (|effect| <= 1%%) -> %s" % (aa["pct"], "VALID" if aa_ok else "INVALID (no exception)"))
rl = S[("pgolto-relocs", "pgolto")]
inside = abs(rl["pct"]) <= 1.0 and abs(rl["mu"]) <= aa["reach"]
v.append("- .rodata move: pgolto-relocs vs pgolto %+.2f%% [%+.2f, %+.2f]; %s +-1%% and the A/A reach %.2f%% -> %s"
         % (rl["pct"], rl["lo"], rl["hi"], "inside" if inside else "NOT inside", aa["reach"],
            "the bolt gain is BOLT" if inside else "report bolt vs pgolto-relocs as the BOLT effect; the rest is the relink"))
bb = S[("bolt", "pgolto-relocs")]
v.append("- BOLT: bolt vs pgolto-relocs %+.2f%% [%+.2f, %+.2f]; kill if under 1.5%% -> %s"
         % (bb["pct"], bb["lo"], bb["hi"], "KILL further BOLT/Propeller work" if -bb["pct"] < 1.5 else "KEEP"))
ao = S[("autofdo-order", "autofdo")]
v.append("- autofdo+order: vs autofdo %+.2f%% [%+.2f, %+.2f]; keep if it saves at least 3%% -> %s"
         % (ao["pct"], ao["lo"], ao["hi"], "KEEP" if -ao["pct"] >= 3 else "not kept (under 3%)"))
if w2:
    W = json.load(open(w2 + "/results.json"))["analysis"]
    g_p = 1 - math.exp(st.mean(get(W, SH, "pgolto", "opt")) / 100)
    # chained: autofdo-order/opt = (autofdo-order/pgolto here) x (pgolto/opt in w2)
    r_ao = math.exp(S[("autofdo-order", "pgolto")]["mu"] / 100) * (1 - g_p)
    r_a = math.exp(S[("autofdo", "pgolto")]["mu"] / 100) * (1 - g_p)
    v.append("- share of the pgolto gain on s (CHAINED through w2's pgolto/opt %.4f): autofdo %.0f%%, autofdo+order %.0f%%"
             % (1 - g_p, (1 - r_a) / g_p * 100, (1 - r_ao) / g_p * 100))
L += v + [""]
# counters
cell = defaultdict(list)
for m in legs:
    if m.get("warmup") or m.get("superseded") or not m["verdict"]["valid"]:
        continue
    cell[m["arm"]].append({k: x / m["responses"] for k, x in (m.get("perf_raw") or {}).items()})
ARMS = ["pgolto", "pgolto-A2", "pgolto-relocs", "bolt", "autofdo", "autofdo-order"]


def mean(a, fn):
    xs = []
    for p in cell[a]:
        try:
            xs.append(fn(p))
        except (KeyError, ZeroDivisionError):
            pass
    return st.mean(xs) if xs else float("nan")


M = [("instructions:u (k)", lambda p: p["instructions:u"] / 1e3), ("cycles:u (k)", lambda p: p["cycles:u"] / 1e3),
     ("cycles:k (k)", lambda p: p["cycles:k"] / 1e3),
     ("frontend bound % (GA)", lambda p: p["idq_uops_not_delivered.core:u"] / (4 * p["cycles:u"]) * 100),
     ("i-cache misses (GB)", lambda p: p["icache.misses:u"]), ("i-cache stall cycles (k, GB)", lambda p: p["icache.ifdata_stall:u"] / 1e3),
     ("BAClears (GB)", lambda p: p["baclears.any:u"])]
L += ["## Counters on s (user space per response; GA rounds 1,3,5, GB rounds 2,4,6)", "",
      "| metric | " + " | ".join(ARMS) + " |", "|---" * (len(ARMS) + 1) + "|"]
for n, fn in M:
    L.append("| %s | %s |" % (n, " | ".join("%.1f" % mean(a, fn) for a in ARMS)))
warm = [m for m in legs if m.get("warmup")]
L += ["", "Legs: %d scored (%d valid), %d warm-up (%d valid)" % (
    len([m for m in legs if not m.get("warmup")]), len([m for m in legs if not m.get("warmup") and m["verdict"]["valid"]]),
    len(warm), len([m for m in warm if m["verdict"]["valid"]]))]
open(out, "w").write("\n".join(L) + "\n")
print("\n".join(v))
