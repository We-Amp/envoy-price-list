#!/usr/bin/env python3
"""Wave 2 A/B analysis (run w2: arms opt, opt-A2, order, autofdo, pgolto, bolt on shapes s, fh, fl).

Usage: python3 -I analyse_w2.py RUN_DIR OUT_MD
RUN_DIR holds results.json and legs.jsonl of the w2 run. Writes OUT_MD, prints the rule verdicts.

Per comparison: the mean paired log ratio of `cycles_total` per response, with the t interval
(t(n-1) x SE) and the widened interval 1.96 x sqrt(SE^2 + 0.34^2); the decision interval is the
wider of the two. Also the A/A reach (|mean| + t half-width of opt-A2 vs opt) and the counter means
per arm and shape.

Kill rules, fixed before the run ("gain" = minus the effect vs the reference, in %):
  order     KILL when its gain vs opt is under 3% on s AND on fh, else KEEP.
  autofdo   share kept = (1 - exp(mu_autofdo/100)) / (1 - exp(mu_pgolto/100)), both vs opt
            (mu = mean log-% effect). KILL when the share is under 50% on s AND on fh, else KEEP.
            Per-round shares with a t interval are reported alongside.
  bolt      KILL when its gain vs pgolto is under 1.5% on two or more of the three shapes, else KEEP.
  validity  pgolto's gain vs opt on s must be within 35-45% (else OUTSIDE), and opt-A2 vs opt must
            be within +-1% on every shape (else the run is NOT OK).
"""
import json
import math
import statistics as st
import sys
from collections import defaultdict

run, out = sys.argv[1], sys.argv[2]
res = json.load(open(run + "/results.json"))
legs = [json.loads(x) for x in open(run + "/legs.jsonl")]
A = res["analysis"]
SHAPES = ["s", "fh", "fl"]
T975 = {5: 2.571, 6: 2.447, 7: 2.365, 8: 2.306, 9: 2.262, 10: 2.228, 11: 2.201}
L = []


def comp(shape, arm, ref, metric="cycles_total"):
    for c in A["shapes"][shape]["comparisons"]:
        if c["arm"] == arm and c.get("reference", A["base_arm"]) == ref:
            return c.get(metric)
    # all_pairs rows name the reference; fall back to searching the reverse pair
    for c in A["shapes"][shape]["comparisons"]:
        if c["arm"] == ref and c.get("reference") == arm and c.get(metric):
            m = dict(c[metric])
            p = dict(m["paired"])
            p["log_pcts"] = [-x for x in p["log_pcts"]]
            m["paired"] = p
            return m
    return None


def stats(m):
    """mean log-%, t half-width, widened half-width, effect as %, n, won."""
    x = m["paired"]["log_pcts"]
    n = len(x)
    mu = st.mean(x)
    se = st.stdev(x) / math.sqrt(n)
    hw = T975.get(n - 1, 2.0) * se
    whw = 1.96 * math.sqrt(se ** 2 + 0.34 ** 2)
    won = sum(1 for v in x if v < 0)
    return {"mu": mu, "hw": hw, "whw": whw, "n": n, "won": won, "pct": (math.exp(mu / 100) - 1) * 100,
            "x": x, "wide": max(hw, whw)}


def pc(x):  # log-% -> %
    return (math.exp(x / 100) - 1) * 100


def fmt(s):
    # the decision interval is the wider of t and widened (the method's widened must never be narrower)
    return "%+.2f%% [%+.2f, %+.2f] (%s) %d/%d won" % (
        s["pct"], pc(s["mu"] - s["wide"]), pc(s["mu"] + s["wide"]), "t" if s["hw"] >= s["whw"] else "widened",
        s["won"], s["n"])


# every comparison row's reference
for sh in SHAPES:
    for c in A["shapes"][sh]["comparisons"]:
        c.setdefault("reference", c.get("ref", A["base_arm"]))

L.append("# W2 analysis (generated by analyse_w2.py)\n")
L.append("Primary metric `cycles_total` per response. Effect = mean paired log ratio as a percent; t = 95%% t "
         "interval; widened = mean ± 1.96*sqrt(SE^2 + 0.34^2); both computed on log ratios, shown as %%. Rounds done: %s.\n"
         % A.get("rounds_done"))
pairs = [("opt-A2", "opt"), ("order", "opt"), ("autofdo", "opt"), ("pgolto", "opt"), ("bolt", "opt"),
         ("bolt", "pgolto"), ("autofdo", "pgolto")]
S = {}
L.append("| comparison | " + " | ".join(SHAPES) + " |")
L.append("|---|---|---|---|")
for a, r in pairs:
    row = []
    for sh in SHAPES:
        m = comp(sh, a, r)
        if m is None:
            row.append("n/a")
            continue
        s = stats(m)
        S[(a, r, sh)] = s
        row.append(fmt(s))
    L.append("| %s vs %s | %s |" % (a, r, " | ".join(row)))
L.append("")
aa = {sh: S.get(("opt-A2", "opt", sh)) for sh in SHAPES}
L.append("A/A reach (|mean| + t half-width of opt-A2 vs opt, log-%%): " + ", ".join(
    "%s %.2f%%" % (sh, abs(aa[sh]["mu"]) + aa[sh]["hw"]) for sh in SHAPES if aa[sh]) + "\n")

# kill rules (fixed before the run; stated in the docstring)
L.append("## Kill rules (fixed before the run)\n")


def gain(a, sh):
    s = S.get((a, "opt", sh))
    return -s["pct"] if s else float("nan")


v = []
o = {sh: gain("order", sh) for sh in SHAPES}
order_kill = o["s"] < 3 and o["fh"] < 3
v.append("- order: gain vs opt s %.2f%%, fh %.2f%% (fl %.2f%%); kill if under 3%% on s AND fh -> %s"
         % (o["s"], o["fh"], o["fl"], "KILL" if order_kill else "KEEP"))
kept = {}
for sh in SHAPES:
    ga, gp = 1 - math.exp(S[("autofdo", "opt", sh)]["mu"] / 100), 1 - math.exp(S[("pgolto", "opt", sh)]["mu"] / 100)
    kept[sh] = ga / gp if gp else float("nan")
af_kill = kept["s"] < 0.5 and kept["fh"] < 0.5
# per-round shares and a t interval on them (6 paired rounds)
shr = {}
for sh in SHAPES:
    xa, xp = S[("autofdo", "opt", sh)]["x"], S[("pgolto", "opt", sh)]["x"]
    r = [(1 - math.exp(a / 100)) / (1 - math.exp(b / 100)) for a, b in zip(xa, xp)]
    se = st.stdev(r) / math.sqrt(len(r))
    shr[sh] = (st.mean(r), st.mean(r) - T975[len(r) - 1] * se, st.mean(r) + T975[len(r) - 1] * se, r)
v.append("- autofdo: share of the pgolto gain kept s %.0f%%, fh %.0f%% (fl %.0f%%); kill if under 50%% on s and fh -> %s"
         % (kept["s"] * 100, kept["fh"] * 100, kept["fl"] * 100, "KILL" if af_kill else "KEEP"))
for sh in SHAPES:
    m, lo, hi, r = shr[sh]
    v.append("  share %s: per-round mean %.3f [t %.3f, %.3f]; rounds above 0.5: %d of %d"
             % (sh, m, lo, hi, sum(1 for x in r if x > 0.5), len(r)))
if all(("bolt", "pgolto", sh) in S for sh in SHAPES):
    b = {sh: -S[("bolt", "pgolto", sh)]["pct"] for sh in SHAPES}
    nb = sum(1 for sh in SHAPES if b[sh] < 1.5)
    v.append("- bolt: gain vs pgolto s %.2f%%, fh %.2f%%, fl %.2f%%; kill if under 1.5%% on two of three -> %s"
             % (b["s"], b["fh"], b["fl"], "KILL" if nb >= 2 else "KEEP"))
p = gain("pgolto", "s")
v.append("- pgolto validity: %.1f%% vs opt on s; band 35-45%% -> %s" % (p, "OK" if 35 <= p <= 45 else "OUTSIDE"))
aa_ok = all(aa[sh] and abs(aa[sh]["pct"]) <= 1.0 for sh in SHAPES)
v.append("- run validity: opt-A2 vs opt within ±1%% on every shape -> %s" % ("OK" if aa_ok else "NOT OK"))
L += v
L.append("")

# counters per arm and shape (means over the rounds of each group)
cell = defaultdict(list)
inval = []
for m in legs:
    if not m["verdict"]["valid"]:
        inval.append((m["leg_id"], m["verdict"]["reasons"]))
        continue
    pr = {k: x / m["responses"] for k, x in (m.get("perf_raw") or {}).items()}
    cell[(m["arm"], m["shape"])].append(pr)
ARMS = ["opt", "opt-A2", "order", "autofdo", "pgolto", "bolt"]


def mean(a, sh, fn):
    xs = []
    for pr in cell[(a, sh)]:
        try:
            xs.append(fn(pr))
        except (KeyError, ZeroDivisionError):
            pass
    return st.mean(xs) if xs else float("nan")


METRICS = [
    ("instructions:u /req (k)", lambda p: p["instructions:u"] / 1e3),
    ("cycles:u /req (k)", lambda p: p["cycles:u"] / 1e3),
    ("cycles:k /req (k)", lambda p: p["cycles:k"] / 1e3),
    ("user IPC", lambda p: p["instructions:u"] / p["cycles:u"]),
    ("frontend bound (user, GA)", lambda p: p["idq_uops_not_delivered.core:u"] / (4 * p["cycles:u"]) * 100),
    ("retiring (user, GA)", lambda p: p["uops_retired.retire_slots:u"] / (4 * p["cycles:u"]) * 100),
    ("i-cache misses /req (GB)", lambda p: p["icache.misses:u"]),
    ("i-cache stall / cycles:u (GB)", lambda p: p["icache.ifdata_stall:u"] / p["cycles:u"] * 100),
    ("BAClears /req (GB)", lambda p: p["baclears.any:u"]),
]
L.append("## Counters (mean over valid legs; GA = rounds 1,3,5, GB = rounds 2,4,6)\n")
for sh in SHAPES:
    L.append("### %s\n" % sh)
    L.append("| metric | " + " | ".join(ARMS) + " |")
    L.append("|---" * (len(ARMS) + 1) + "|")
    for name, fn in METRICS:
        L.append("| %s | %s |" % (name, " | ".join("%.1f" % mean(a, sh, fn) for a in ARMS)))
    L.append("")
L.append("Invalid legs: %d %s" % (len(inval), inval[:10]))
open(out, "w").write("\n".join(L) + "\n")
print("\n".join(v))
