#!/usr/bin/env python3
"""Wave 5 track I A/B analysis (run w5i: arms official, official-A2, order, pgolto, pgolto-v2 [, opt] on
shapes s, fh, fl; arm64 VM). Helpers copied from wave 2's analyse_w2.py.

Usage: python3 -I analyse_w5i.py RUN_DIR OUT_MD

Rules, fixed before the run ("gain" = minus the effect vs the reference, in %; decision
interval = the wider of t and widened 1.96*sqrt(SE^2+0.34^2)):
  run       official-A2 vs official within +-1% on every shape AND its decision interval contains 0,
            else the run is NOT OK (invalid, no exception).
  pgolto    no kill. Validity band: gain vs official on s within 20-50%, else OUTSIDE (stop, find out why).
  order     vs official (vs opt when opt is an arm): KILL when its gain is under 3% on s AND on fh.
  pgolto-v2 vs pgolto: CLAIM only when |effect| >= 2% and the decision interval excludes 0 and |effect| exceeds
            the A/A reach (|mean| + t half-width of official-A2 vs official) on that shape; otherwise
            "no resolved difference; at most X%" (X = the larger end of the decision interval).
"""

import json
import math
import statistics as st
import sys
from collections import defaultdict

run, out = sys.argv[1], sys.argv[2]
res = json.load(open(run + "/results.json"))
legs = [json.loads(x) for x in open(run + "/legs.jsonl")]
A = res["analysis"]
SHAPES = ["s", "fh", "fl"]
T975 = {5: 2.571, 6: 2.447, 7: 2.365, 8: 2.306, 9: 2.262, 10: 2.228, 11: 2.201, 12: 2.179, 13: 2.160}
L = []


def comp(shape, arm, ref, metric="cycles_total"):
    for c in A["shapes"][shape]["comparisons"]:
        if c["arm"] == arm and c.get("reference", A["base_arm"]) == ref:
            return c.get(metric)
    # all_pairs rows name the reference; fall back to searching the reverse pair
    for c in A["shapes"][shape]["comparisons"]:
        if c["arm"] == ref and c.get("reference") == arm and c.get(metric):
            m = dict(c[metric])
            p = dict(m["paired"])
            p["log_pcts"] = [-x for x in p["log_pcts"]]
            m["paired"] = p
            return m
    return None


def stats(m):
    """mean log-%, t half-width, widened half-width, effect as %, n, won."""
    x = m["paired"]["log_pcts"]
    n = len(x)
    mu = st.mean(x)
    se = st.stdev(x) / math.sqrt(n)
    hw = T975.get(n - 1, 2.0) * se
    whw = 1.96 * math.sqrt(se ** 2 + 0.34 ** 2)
    won = sum(1 for v in x if v < 0)
    return {"mu": mu, "hw": hw, "whw": whw, "n": n, "won": won, "pct": (math.exp(mu / 100) - 1) * 100,
            "x": x, "wide": max(hw, whw)}


# The ordering-file rows of this run are held: we do not quote them as a result.
HELD_NOTE = ("**Held, not confirmed: the `order` rows.** The control (the same code in a separate file, where no "
             "effect is expected) was not run on this host: `order` and `official` are different files made in different "
             "ways, so this run cannot tell a code-layout effect from a file-placement effect. On bare metal (wave 6 "
             "track J) the file control was null and the ordering file gave 4-7%. The figures here stay in the data; we "
             "do not quote them as a result.")


def pc(x):  # log-% -> %
    return (math.exp(x / 100) - 1) * 100


def fmt(s):
    # the decision interval is the wider of t and widened (the method's widened must never be narrower)
    return "%+.2f%% [%+.2f, %+.2f] (%s) %d/%d won" % (
        s["pct"], pc(s["mu"] - s["wide"]), pc(s["mu"] + s["wide"]), "t" if s["hw"] >= s["whw"] else "widened",
        s["won"], s["n"])


# every comparison row's reference
for sh in SHAPES:
    for c in A["shapes"][sh]["comparisons"]:
        c.setdefault("reference", c.get("ref", A["base_arm"]))

arm_names = sorted({m["arm"] for m in legs})
OREF = "opt" if "opt" in arm_names else "official"
L.append("# W5I analysis (generated by analyse_w5i.py)\n")
L.append("Primary metric `cycles_total` per response. Effect = mean paired log ratio as a percent; decision "
         "interval = the wider of the 95%% t interval and mean +- 1.96*sqrt(SE^2 + 0.34^2); shown as %%. Rounds done: %s.\n"
         % A.get("rounds_done"))
pairs = [("official-A2", "official"), ("order", OREF), ("pgolto", "official"), ("pgolto-v2", "official"),
         ("pgolto-v2", "pgolto"), ("order", "official")]
if OREF == "opt":
    pairs.append(("opt", "official"))
pairs = list(dict.fromkeys(pairs))
S = {}
L.append("| comparison | " + " | ".join(SHAPES) + " |")
L.append("|---|---|---|---|")
for a, r in pairs:
    row = []
    for sh in SHAPES:
        m = comp(sh, a, r)
        if m is None:
            row.append("n/a")
            continue
        s = stats(m)
        S[(a, r, sh)] = s
        row.append(fmt(s))
    held = " (HELD, not confirmed)" if a == "order" else ""
    L.append("| %s vs %s%s | %s |" % (a, r, held, " | ".join(row)))
L.append("")
L.append(HELD_NOTE + "\n")
aa = {sh: S.get(("official-A2", "official", sh)) for sh in SHAPES}
reach = {sh: abs(aa[sh]["mu"]) + aa[sh]["hw"] for sh in SHAPES if aa[sh]}
L.append("A/A reach (|mean| + t half-width of official-A2 vs official, log-%): " + ", ".join(
    "%s %.2f" % (sh, reach[sh]) for sh in SHAPES if sh in reach) + "\n")
L.append("## Rules (fixed before the run)\n")


def gain(a, ref, sh):
    s = S.get((a, ref, sh))
    return -s["pct"] if s else float("nan")


v = []
aa_ok = all(aa[sh] and abs(aa[sh]["pct"]) <= 1.0 and pc(aa[sh]["mu"] - aa[sh]["wide"]) <= 0 <= pc(aa[sh]["mu"] + aa[sh]["wide"])
            for sh in SHAPES)
v.append("- run validity: official-A2 vs official within +-1%% and interval contains 0 on every shape -> %s"
         % ("OK" if aa_ok else "NOT OK (run invalid)"))
p = gain("pgolto", "official", "s")
v.append("- pgolto validity: gain %.1f%% vs official on s; band 20-50%% -> %s" % (p, "OK" if 20 <= p <= 50 else "OUTSIDE"))
v.append("  pgolto gain vs official: " + ", ".join("%s %.1f%%" % (sh, gain("pgolto", "official", sh)) for sh in SHAPES))
o = {sh: gain("order", OREF, sh) for sh in SHAPES}
v.append("- order: gain vs %s s %.2f%%, fh %.2f%% (fl %.2f%%); kill if under 3%% on s AND fh -> %s"
         % (OREF, o["s"], o["fh"], o["fl"], "KILL" if (o["s"] < 3 and o["fh"] < 3) else
            "HELD (above the kill line, but not confirmed: no file control on this host; see the note above)"))
for sh in SHAPES:
    s = S.get(("pgolto-v2", "pgolto", sh))
    if not s:
        v.append("- pgolto-v2 vs pgolto %s: n/a" % sh)
        continue
    lo, hi = pc(s["mu"] - s["wide"]), pc(s["mu"] + s["wide"])
    claim = abs(s["pct"]) >= 2 and (hi < 0 or lo > 0) and abs(s["mu"]) > reach.get(sh, 1e9)
    v.append("- pgolto-v2 vs pgolto %s: %s -> %s" % (sh, fmt(s), "CLAIM" if claim else
             "no resolved difference; at most %.1f%%" % max(abs(lo), abs(hi))))
L += v
L.append("")

cell = defaultdict(list)
inval = []
for m in legs:
    if not m["verdict"]["valid"]:
        inval.append((m["leg_id"], m["verdict"]["reasons"]))
        continue
    pr = {k: x / m["responses"] for k, x in (m.get("perf_raw") or {}).items()}
    cell[(m["arm"], m["shape"])].append(pr)
ARMS = [a for a in ["official", "official-A2", "opt", "order", "pgolto", "pgolto-v2"] if a in arm_names]


def mean(a, sh, fn):
    xs = []
    for pr in cell[(a, sh)]:
        try:
            xs.append(fn(pr))
        except (KeyError, ZeroDivisionError):
            pass
    return st.mean(xs) if xs else float("nan")


METRICS = [
    ("instructions:u /req (k)", lambda p: p["instructions:u"] / 1e3),
    ("cycles:u /req (k)", lambda p: p["cycles:u"] / 1e3),
    ("cycles:k /req (k)", lambda p: p["cycles:k"] / 1e3),
    ("user IPC", lambda p: p["instructions:u"] / p["cycles:u"]),
    ("stall_frontend / cycles:u % (GA)", lambda p: p["stall_frontend:u"] / p["cycles:u"] * 100),
    ("stall_backend / cycles:u % (GA)", lambda p: p["stall_backend:u"] / p["cycles:u"] * 100),
    ("L1I refills /req (GB)", lambda p: p["l1i_cache_refill:u"]),
    ("L1I TLB refills /req (GB)", lambda p: p["l1i_tlb_refill:u"]),
]
L.append("## Counters (mean over valid legs; GA and GB rotate by round)\n")
for sh in SHAPES:
    L.append("### %s\n" % sh)
    L.append("| metric | " + " | ".join(ARMS) + " |")
    L.append("|---" * (len(ARMS) + 1) + "|")
    for name, fn in METRICS:
        L.append("| %s | %s |" % (name, " | ".join("%.2f" % mean(a, sh, fn) for a in ARMS)))
    L.append("")
L.append("Invalid legs: %d %s" % (len(inval), inval[:10]))
open(out, "w").write("\n".join(L) + "\n")
print("\n".join(v))
