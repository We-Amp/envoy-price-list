#!/usr/bin/env python3
"""Wave 6 track J A/B analysis (run w6j, arm64 bare metal, a Neoverse N3 host; arms official, official-A2, opt-file,
order, pgolto, autofdo, bolt; shapes s, fh, fl). Helpers from analyse_w5i.py / analyse_w2.py.

Usage: python3 -I analyse_w6j.py RUN_DIR OUT_MD

Rules fixed before any data of the run (2026-11-22); decision interval = wider of t and
1.96*sqrt(SE^2+0.34^2); "reach" = |mean| + t half-width of official-A2 vs official:
  run       official-A2 vs official within +-1% on every shape AND the interval contains 0, else NOT OK.
  opt-file  vs official: the same gate -> "no file effect" (order vs official may be read as layout), else
            "file effect present" (only order vs opt-file is layout).
  order     vs opt-file (the layout row): KILL if under 3% fewer cycles on s AND fh.
  pgolto    vs official: validity band 20-50% on s (I's row is a reading only).
  autofdo   share = (1 - a/o) / (1 - p/o) vs official (% change): KILL if under 0.5 on s AND fh.
  bolt      vs pgolto: KILL if under 1.5% fewer cycles on two or more shapes; a pass is quoted only when the interval
            excludes 0 and lies outside the A/A reach.
"""
import json
import math
import statistics as st
import sys
from collections import defaultdict

run, out = sys.argv[1], sys.argv[2]
res = json.load(open(run + "/results.json"))
legs = [json.loads(x) for x in open(run + "/legs.jsonl")]
A = res["analysis"]
SHAPES = ["s", "fh", "fl"]
T975 = {5: 2.571, 6: 2.447, 7: 2.365, 8: 2.306, 9: 2.262, 10: 2.228, 11: 2.201, 12: 2.179, 13: 2.160}
L = []


def comp(shape, arm, ref, metric="cycles_total"):
    for c in A["shapes"][shape]["comparisons"]:
        if c["arm"] == arm and c.get("reference", A["base_arm"]) == ref:
            return c.get(metric)
    # all_pairs rows name the reference; fall back to searching the reverse pair
    for c in A["shapes"][shape]["comparisons"]:
        if c["arm"] == ref and c.get("reference") == arm and c.get(metric):
            m = dict(c[metric])
            p = dict(m["paired"])
            p["log_pcts"] = [-x for x in p["log_pcts"]]
            m["paired"] = p
            return m
    return None


def stats(m):
    """mean log-%, t half-width, widened half-width, effect as %, n, won."""
    x = m["paired"]["log_pcts"]
    n = len(x)
    mu = st.mean(x)
    se = st.stdev(x) / math.sqrt(n)
    hw = T975.get(n - 1, 2.0) * se
    whw = 1.96 * math.sqrt(se ** 2 + 0.34 ** 2)
    won = sum(1 for v in x if v < 0)
    return {"mu": mu, "hw": hw, "whw": whw, "n": n, "won": won, "pct": (math.exp(mu / 100) - 1) * 100,
            "x": x, "wide": max(hw, whw)}


def pc(x):  # log-% -> %
    return (math.exp(x / 100) - 1) * 100


def fmt(s):
    # the decision interval is the wider of t and widened (the method's widened must never be narrower)
    return "%+.2f%% [%+.2f, %+.2f] (%s) %d/%d won" % (
        s["pct"], pc(s["mu"] - s["wide"]), pc(s["mu"] + s["wide"]), "t" if s["hw"] >= s["whw"] else "widened",
        s["won"], s["n"])


# every comparison row's reference
for sh in SHAPES:
    for c in A["shapes"][sh]["comparisons"]:
        c.setdefault("reference", c.get("ref", A["base_arm"]))
arm_names = sorted({m["arm"] for m in legs})
L.append("# W6J analysis (generated by analyse_w6j.py)\n")
L.append("Primary metric `cycles_total` per response; decision interval = wider of t and widened; rounds done: %s.\n" % A.get("rounds_done"))
pairs = [("official-A2", "official"), ("opt-file", "official"), ("order", "opt-file"), ("order", "official"),
         ("pgolto", "official"), ("autofdo", "official"), ("bolt", "pgolto"), ("bolt", "official"), ("pgolto", "order"),
         ("autofdo", "pgolto")]
S = {}
L.append("| comparison | " + " | ".join(SHAPES) + " |")
L.append("|---|---|---|---|")
for a, r in pairs:
    row = []
    for sh in SHAPES:
        m = comp(sh, a, r)
        if m is None:
            row.append("n/a"); continue
        s = stats(m); S[(a, r, sh)] = s; row.append(fmt(s))
    L.append("| %s vs %s | %s |" % (a, r, " | ".join(row)))
L.append("")
aa = {sh: S.get(("official-A2", "official", sh)) for sh in SHAPES}
reach = {sh: abs(aa[sh]["mu"]) + aa[sh]["hw"] for sh in SHAPES if aa[sh]}
L.append("A/A reach: " + ", ".join("%s %.2f%%" % (sh, reach[sh]) for sh in SHAPES if sh in reach) + "\n")


def gate(s):
    return s and abs(s["pct"]) <= 1.0 and pc(s["mu"] - s["wide"]) <= 0 <= pc(s["mu"] + s["wide"])


def gain(a, ref, sh):
    s = S.get((a, ref, sh)); return -s["pct"] if s else float("nan")


v = []
aa_ok = all(gate(aa[sh]) for sh in SHAPES)
v.append("- run validity (A/A within +-1%%, interval contains 0, every shape) -> %s" % ("OK" if aa_ok else "NOT OK (run invalid)"))
fo = all(gate(S.get(("opt-file", "official", sh))) for sh in SHAPES)
v.append("- opt-file vs official (file control) -> %s" % ("no file effect" if fo else "FILE EFFECT PRESENT"))
for sh in SHAPES:
    s = S.get(("opt-file", "official", sh)); v.append("  opt-file vs official %s: %s" % (sh, fmt(s) if s else "n/a"))
o = {sh: gain("order", "opt-file", sh) for sh in SHAPES}
v.append("- order vs opt-file (layout row): gain s %.2f%%, fh %.2f%%, fl %.2f%%; kill if under 3%% on s AND fh -> %s"
         % (o["s"], o["fh"], o["fl"], "KILL" if (o["s"] < 3 and o["fh"] < 3) else "KEEP"))
p = gain("pgolto", "official", "s")
v.append("- pgolto validity: gain %.1f%% vs official on s; band 20-50%% -> %s" % (p, "OK" if 20 <= p <= 50 else "OUTSIDE"))
v.append("  pgolto gain vs official: " + ", ".join("%s %.1f%%" % (sh, gain("pgolto", "official", sh)) for sh in SHAPES)
         + " (reading only: I's VM row 38.2 / 33.7 / 35.5%, another core)")
sh_ = {}
for sh in SHAPES:
    ga, gp = gain("autofdo", "official", sh) / 100, gain("pgolto", "official", sh) / 100
    sh_[sh] = ga / gp if gp else float("nan")
v.append("- autofdo share of the pgolto gain: s %.0f%%, fh %.0f%%, fl %.0f%%; kill if under 50%% on s AND fh -> %s"
         % (sh_["s"] * 100, sh_["fh"] * 100, sh_["fl"] * 100, "KILL" if (sh_["s"] < 0.5 and sh_["fh"] < 0.5) else "KEEP"))
b = {sh: gain("bolt", "pgolto", sh) for sh in SHAPES}
nb = sum(1 for sh in SHAPES if b[sh] < 1.5)
v.append("- bolt vs pgolto: gain s %.2f%%, fh %.2f%%, fl %.2f%%; kill if under 1.5%% on two of three -> %s"
         % (b["s"], b["fh"], b["fl"], "KILL" if nb >= 2 else "KEEP"))
for sh in SHAPES:
    s = S.get(("bolt", "pgolto", sh))
    if s:
        lo, hi = pc(s["mu"] - s["wide"]), pc(s["mu"] + s["wide"])
        q = hi < -reach.get(sh, 1e9) or lo > reach.get(sh, 1e9)
        v.append("  bolt vs pgolto %s: %s -> %s" % (sh, fmt(s), "quotable (interval outside the A/A reach)" if q else "not quotable as a resolved difference"))
L += ["## Rules (fixed before the run)\n"] + v + [""]
cell = defaultdict(list); inval = []
for m in legs:
    if not m["verdict"]["valid"]:
        inval.append((m["leg_id"], m["verdict"]["reasons"])); continue
    pr = {k: x / m["responses"] for k, x in (m.get("perf_raw") or {}).items()}
    cell[(m["arm"], m["shape"])].append(pr)
ARMS = [a for a in ["official", "official-A2", "opt-file", "order", "pgolto", "autofdo", "bolt"] if a in arm_names]


def mean(a, sh, fn):
    xs = []
    for pr in cell[(a, sh)]:
        try:
            xs.append(fn(pr))
        except (KeyError, ZeroDivisionError):
            pass
    return st.mean(xs) if xs else float("nan")


METRICS = [
    ("instructions:u /req (k)", lambda p: p["instructions:u"] / 1e3),
    ("cycles:u /req (k)", lambda p: p["cycles:u"] / 1e3),
    ("cycles:k /req (k)", lambda p: p["cycles:k"] / 1e3),
    ("user IPC", lambda p: p["instructions:u"] / p["cycles:u"]),
    ("stall_frontend / cycles:u % (GA)", lambda p: p["stall_frontend:u"] / p["cycles:u"] * 100),
    ("stall_backend / cycles:u % (GA)", lambda p: p["stall_backend:u"] / p["cycles:u"] * 100),
    ("L1I refills /req (GB)", lambda p: p["l1i_cache_refill:u"]),
    ("L1I TLB refills /req (GB)", lambda p: p["l1i_tlb_refill:u"]),
]
L.append("## Counters (mean over valid legs)\n")
for sh in SHAPES:
    L.append("### %s\n" % sh)
    L.append("| metric | " + " | ".join(ARMS) + " |")
    L.append("|---" * (len(ARMS) + 1) + "|")
    for name, fn in METRICS:
        L.append("| %s | %s |" % (name, " | ".join("%.2f" % mean(a, sh, fn) for a in ARMS)))
    L.append("")
L.append("Invalid legs: %d %s" % (len(inval), inval[:10]))
open(out, "w").write("\n".join(L) + "\n")
print("\n".join(v))
